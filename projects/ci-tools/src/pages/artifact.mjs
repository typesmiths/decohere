import { existsSync } from "node:fs";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { normalize } from "../bench/history.mjs";
import { buildBenchmarkHtml, buildStylesCss } from "./bench-page.mjs";

const branch = process.env.GITHUB_REF_NAME ?? "local";
const sha = process.env.GITHUB_SHA ?? "local";
const outputDir = process.env.PAGES_OUTPUT_DIR ?? "site";

const badgesDir = "projects/ci-tools/dist/ci/badges";
const benchHistoryPath = "projects/ci-tools/dist/ci/bench/bench-history.json";

/** Every badge file under `dir`, relative to it: the manifest restore-badges.mjs reads back. */
async function listBadges(dir, prefix = "") {
	const entries = await readdir(path.join(dir, prefix), { withFileTypes: true });
	const nested = await Promise.all(
		entries.map((entry) =>
			entry.isDirectory()
				? listBadges(dir, path.posix.join(prefix, entry.name))
				: entry.name.endsWith(".svg")
					? [path.posix.join(prefix, entry.name)]
					: [],
		),
	);
	return nested.flat().sort();
}

await rm(outputDir, { recursive: true, force: true });
await mkdir(path.join(outputDir, "data"), { recursive: true });

await writeFile(path.join(outputDir, "styles.css"), buildStylesCss());

// index.html redirects to benchmark.html — no separate dashboard needed
await writeFile(
	path.join(outputDir, "index.html"),
	`<!doctype html><html><head><meta charset="utf-8"/><meta http-equiv="refresh" content="0;url=./benchmark.html"/><title>Decohere Pages</title></head><body><p><a href="./benchmark.html">Benchmarks</a></p></body></html>\n`,
);

// No history yet (first deploy, or cleared) publishes the empty page, not a failure.
const benchHistory = normalize(
	existsSync(benchHistoryPath) ? JSON.parse(await readFile(benchHistoryPath, "utf8")) : null,
);
await writeFile(
	path.join(outputDir, "benchmark.html"),
	buildBenchmarkHtml(benchHistory, { branch, sha }),
);
await writeFile(
	path.join(outputDir, "data", "bench-history.json"),
	`${JSON.stringify(benchHistory, null, 2)}\n`,
);

// Badges are generated by earlier steps (CI status, coverage) or restored from the live site.
if (existsSync(badgesDir)) {
	await cp(badgesDir, path.join(outputDir, "badges"), { recursive: true });
	const badges = await listBadges(badgesDir);
	await writeFile(
		path.join(outputDir, "badges", "manifest.json"),
		`${JSON.stringify({ badges }, null, 2)}\n`,
	);
}

await writeFile(path.join(outputDir, ".nojekyll"), "");
