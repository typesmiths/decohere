#!/usr/bin/env node
/**
 * Publish prerelease version commit via PR
 * Validates working tree, pushes prerelease commit to a release branch,
 * and creates/updates a PR targeting the protected base branch.
 */

import { execSync } from "node:child_process";

function run(command) {
	return execSync(command, { encoding: "utf8" }).trim();
}

function runInherit(command, env) {
	execSync(command, { stdio: "inherit", env });
}

try {
	// Check if working tree is dirty
	const status = run("git status --porcelain");
	if (status.trim().length > 0) {
		console.error(
			"::error::Working tree is dirty after version/dependency sync; refusing to publish with uncommitted changes.",
		);
		console.log(status);
		process.exit(1);
	}

	// Compare HEAD with origin and create a PR branch targeting an explicit base branch.
	const head = run("git rev-parse HEAD");
	const sourceBranch = process.env.GITHUB_REF_NAME || run("git rev-parse --abbrev-ref HEAD");
	const channel = process.env.RELEASE_CHANNEL ?? "beta";
	const baseBranch = process.env.RELEASE_BASE_BRANCH || sourceBranch;
	const releasePrBranch = `release/${channel}-${sourceBranch}-to-${baseBranch}`;
	const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;

	try {
		const origin = run(`git rev-parse origin/${sourceBranch}`);

		if (head !== origin) {
			console.log(
				`Publishing release commit via PR branch origin/${releasePrBranch} (base: origin/${baseBranch})`,
			);
			runInherit(`git push origin HEAD:${releasePrBranch} --force`, process.env);

			if (token == null || token.length === 0) {
				throw new Error("Missing GITHUB_TOKEN/GH_TOKEN for PR upsert");
			}

			const version = process.env.RELEASE_VERSION ?? "(unknown)";
			const ownerRepo = run("git config --get remote.origin.url")
				.replace(/^.*github\.com[:/]/, "")
				.replace(/\.git$/, "");

			runInherit(
				[
					"node projects/ci-tools/src/github/create-or-update-pr.mjs",
					`--title "chore(release): ${channel} ${version}"`,
					`--base "${baseBranch}"`,
					`--head "${releasePrBranch}"`,
					`--body "Automated ${channel} version bump and dependency sync.\\n\\n- Channel: ${channel}\\n- Version: ${version}\\n- Source branch: ${sourceBranch}\\n- Base branch: ${baseBranch}\\n- Source commit: ${head}\\n\\nGenerated by pull-request workflow."`,
					`--owner "${ownerRepo.split("/")[0]}"`,
					`--repo "${ownerRepo.split("/")[1]}"`,
				].join(" "),
				{ ...process.env, GITHUB_TOKEN: token },
			);
		} else {
			console.log("No prerelease version commit to push.");
		}
	} catch (err) {
		const message = err?.message ?? "";
		if (
			message.includes(`origin/${sourceBranch}`) &&
			message.includes("Needed a single revision")
		) {
			console.log(`Remote branch origin/${sourceBranch} not found, skipping push.`);
		} else {
			console.error("::error::Failed to publish release commit via PR branch.");
			throw err;
		}
	}
} catch (e) {
	console.error(`Push failed: ${e.message}`);
	process.exit(1);
}
