import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { injectable } from "@decohere/crucible/decorators";
import { packageAliases, Workspace } from "@decohere/workspace";
import type { Action } from "@decohere/devkit/cli";
import { ActionResponse } from "@decohere/devkit/cli";
import { scribe } from "@decohere/scribe";

export const PATHS_FILE = "tsconfig.paths.json";

export type PathsOptions = {
	/** Fail if the file is missing or out of date, instead of writing it. */
	check?: boolean;
};

export type PathsResponse = {
	file: string;
	changed: boolean;
	succeeded: boolean;
	error?: string;
};

/**
 * Writes `tsconfig.paths.json`: tsconfig `paths` for every workspace package and the subpaths it
 * exports, from the workspace aliases. Without `node_modules` links, `tsc` finds workspace
 * packages only through `paths`; generating them keeps them in step with what Flux, the Vitest
 * plugin and builds resolve. The root tsconfig extends the file.
 */
@injectable()
export class Paths implements Action<PathsOptions> {
	#logger = scribe.logger(Paths.name);
	public constructor(private readonly workspace: Workspace) {}

	public async run(options: PathsOptions): Promise<ActionResponse<PathsResponse>> {
		const file = path.join(this.workspace.rootDir, PATHS_FILE);
		const content = Paths.render(this.workspace);
		const current = existsSync(file) ? await readFile(file, "utf8") : null;
		const changed = current !== content;

		if (options.check) {
			if (!changed) {
				return ActionResponse.Success<PathsResponse>(Paths.name, [
					{ file, changed, succeeded: true },
				]);
			}
			const error = `${PATHS_FILE} is out of date. Run \`forge paths\` to update it.`;
			this.#logger.error(error);
			return ActionResponse.Error<PathsResponse>(Paths.name, [
				{ file, changed, succeeded: false, error },
			]);
		}

		if (changed) {
			await writeFile(file, content);
			this.#logger.info(`Wrote ${PATHS_FILE}`);
		}
		return ActionResponse.Success<PathsResponse>(Paths.name, [
			{ file, changed, succeeded: true },
		]);
	}

	/** The file's content: convention and exported subpaths only, never the tsconfig's own paths. */
	public static render(workspace: Workspace): string {
		const rootDir = path.resolve(workspace.rootDir);
		const { paths } = packageAliases.build(workspace.getProjects("debug"), {
			baseUrl: rootDir,
		});
		const sorted = Object.fromEntries(
			Object.keys(paths)
				.sort()
				.map((key) => [key, (paths[key] ?? []).map((target) => `./${target}`)]),
		);
		const json = {
			$comment: "Generated by `forge paths` from the workspace packages. Do not edit.",
			compilerOptions: { paths: sorted },
		};
		return `${JSON.stringify(json, null, 2)}\n`;
	}
}
